/*
Purpose:
Segment customers into Low, Mid, and High Lifetime Value (LTV)
groups using the 25th and 75th percentiles of customer lifetime revenue.

The analysis calculates:
- Total lifetime revenue per customer.
- LTV percentile thresholds.
- Customer value segments.
- Total revenue, customer count, and average LTV per segment.
*/

WITH customer_ltv AS (

    /*
    Step 1: Calculate the total lifetime revenue for each customer.

    GROUP BY ensures each customer has one aggregated LTV value.
    */

    SELECT
        customerkey,
        clean_name,
        SUM(net_rev) AS total_ltv
    FROM cohort_analysis
    GROUP BY
        customerkey,
        clean_name

), customer_segmentation AS (

    /*
    Step 2: Calculate the 25th and 75th percentile thresholds.

    PERCENTILE_CONT calculates continuous percentiles:
    - 25th percentile: Lower-value threshold.
    - 75th percentile: Upper-value threshold.

    These thresholds are used to divide customers into three segments.
    */

    SELECT
        PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY total_ltv) AS ltv_25th_percentile,
        PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY total_ltv) AS ltv_75th_percentile
    FROM customer_ltv

), segment_values AS (

    /*
    Step 3: Assign each customer to an LTV segment.

    Low-value:
        LTV below the 25th percentile.

    Mid-value:
        LTV between the 25th and 75th percentiles.

    High-value:
        LTV above the 75th percentile.
    */

    SELECT
        c.*,
        CASE
            WHEN c.total_ltv < cs.ltv_25th_percentile THEN '1-low-value'
            WHEN c.total_ltv <= cs.ltv_75th_percentile THEN '2-mid-value'
            ELSE '3-high-value'
        END AS customer_segment

    FROM customer_ltv c
    CROSS JOIN customer_segmentation cs

)

/*
Step 4: Aggregate the results by customer segment.

Metrics:
- Total LTV: Combined lifetime revenue generated by each segment.
- Customer Count: Number of customers in each segment.
- Average LTV: Average lifetime revenue per customer.

Results are ordered by segment in descending order.
*/

SELECT
    customer_segment,
    SUM(total_ltv) AS total_ltv,
    COUNT(customerkey) AS customer_count,
    SUM(total_ltv) / COUNT(customerkey) AS avg_ltv

FROM segment_values
GROUP BY customer_segment
ORDER BY customer_segment DESC;
